// Generates components/icons/index.tsx from the Solar icon set.
// Run: npm run generate-solar-icons
//
// Why generate instead of using @iconify/react directly: this app is an
// offline-capable PWA, and Iconify's <Icon icon="solar:..."> fetches icon data
// from its API at runtime. Inlining the ~55 icons we actually use keeps the
// app working offline and adds no runtime dependency — @iconify-json/solar is
// a devDependency only.
//
// To restyle the whole app, change STYLE below and re-run. Solar ships
// linear / outline / bold / broken / bold-duotone / line-duotone.
